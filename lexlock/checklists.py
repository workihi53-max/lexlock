def detect_contract_type(text: str) -> str:
    """Определяет тип договора по ключевым маркерам; по умолчанию «услуги»."""
    lowered = (text or "").lower()
    best_type = "услуги"
    best_score = 0
    for name, markers in CONTRACT_TYPES.items():
        score = sum(1 for marker in markers if marker in lowered)
        if score > best_score:
            best_type, best_score = name, score
    return best_type


def evaluate(text: str, contract_type: str) -> list[dict]:
    """Проверяет условия выбранного типа; возвращает список с флагом present."""
    lowered = (text or "").lower()
    rules = CHECKLISTS.get(contract_type, CHECKLISTS["услуги"])
    return [
        {
            "code": code,
            "item": title,
            "present": any(marker in lowered for marker in markers),
        }
        for code, title, markers in rules
    ]
